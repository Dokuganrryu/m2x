pub(crate) const fn has_glyph(byte: u8) -> bool {
    byte == b' ' || !matches!(character(byte), BLANK)
}

#[cfg(all(test, feature = "screen2"))]
mod tests {
    use super::*;

    #[test]
    fn the_screen2_letters_d_g_k_m_x_have_the_preview_rows() {
        for (byte, rows) in [
            (b'D', [0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E]),
            (b'G', [0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F]),
            (b'K', [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11]),
            (b'M', [0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11]),
            (b'W', [0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A]),
            (b'X', [0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11]),
        ] {
            assert_eq!(character(byte), GlyphRows(rows), "{}", byte as char);
            assert!(has_glyph(byte));
        }
    }
}
