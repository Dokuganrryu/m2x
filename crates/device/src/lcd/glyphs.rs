pub(crate) const GLYPH_WIDTH: u8 = 5;
pub(crate) const GLYPH_HEIGHT: u8 = 7;
pub(crate) const GLYPH_ADVANCE: u8 = GLYPH_WIDTH + 1;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct GlyphRows([u8; GLYPH_HEIGHT as usize]);

impl GlyphRows {
    pub(crate) const fn lit(self, column: u8, row: u8) -> bool {
        self.0[row as usize] & (1 << (GLYPH_WIDTH - 1 - column)) != 0
    }
}

#[cfg(not(feature = "screen2"))]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Icon {
    Lock,
    Play,
    Record,
}

#[cfg(not(feature = "screen2"))]
impl Icon {
    pub(crate) const fn rows(self) -> GlyphRows {
        match self {
            Icon::Lock => GlyphRows([0x0E, 0x11, 0x11, 0x1F, 0x1B, 0x1B, 0x1F]),
            Icon::Play => GlyphRows([0x10, 0x18, 0x1C, 0x1E, 0x1C, 0x18, 0x10]),
            Icon::Record => GlyphRows([0x00, 0x0E, 0x1F, 0x1F, 0x1F, 0x0E, 0x00]),
        }
    }
}

const BLANK: GlyphRows = GlyphRows([0; GLYPH_HEIGHT as usize]);

